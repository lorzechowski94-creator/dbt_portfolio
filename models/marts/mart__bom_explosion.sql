{%- set max_depth = 21 -%}
{#- Read from the usage link that brought the node in, so a top-level part has none. -#}
{%- set usage_columns = [
    'wtpart_usage_key',
    'parent_wtpart_master_key',
    'parent_part_number',
    'component_quantity',
    'spare_part_indicator',
    'lowest_replaceable_unit',
    'reference_designator'
] -%}
{#- Read from the part itself, so the top-level part (level 0) has them too. -#}
{%- set part_columns = [
    'component_wtpart_master_key',
    'part_number',
    'part_name',
    'view'
] -%}
-- BOM explosion: one row per node of every product structure, with each latest
-- part version in the Design / Manufacturing / Service views as a top-level part.
-- Grain: top-level part (master key + view) + the path of usage links down to the
-- node (bom_path_key).
--
-- FIXED DEPTH, NOT RECURSIVE. The tree is unrolled into max_depth left joins of
-- parent_child, generated by the loops below. A structure deeper than that is cut
-- at max_depth, and is_depth_truncated marks the rows where it happened.
--
-- STOP ROWS. Left joins alone give one row per root-to-LEAF path, so an assembly
-- would never get a row of its own. parent_child therefore adds one all-null child
-- per parent: the path that takes it ends at the parent, which is how every
-- assembly, not only every leaf, becomes a row.
--
-- A ROW'S NODE IS ITS DEEPEST LEVEL WITH A PART, and every node attribute is read
-- from that level alone. Coalescing a column across the levels instead hands a node
-- its parent's value wherever its own is null: a reference designator or a
-- spare-part flag inherited from the assembly above.
--
-- NO DISTINCT. A sub-assembly used twice under one parent is two branches, each
-- with its whole subtree, as it is physically built. Their rows differ only in the
-- usage path, so a DISTINCT would merge the copies and under-count every quantity
-- that rolls up through them.

with bom_usage as (
    select * from {{ ref('material_bom') }}
),

top_level_parts as (
    select *
    from {{ ref('part_version') }}
    where
        view in ('Design', 'Manufacturing', 'Service')
        and latest_view_iteration
),

-- every part that has children, in the view it has them in
parents as (
    select distinct
        parent_wtpart_master_key1 as join_parent_key,
        parent_part_view as join_parent_view
    from bom_usage
),

parent_child as (
    select
        parent_wtpart_master_key1 as join_parent_key,
        parent_part_view as join_parent_view,
        wtpart_usage_key,
        parent_wtpart_master_key,
        parent_part_number,
        component_quantity,
        spare_part_indicator,
        lowest_replaceable_unit,
        reference_designator,
        component_wtpart_master_key,
        part_number,
        part_name,
        part_view as view
    from bom_usage

    union all

    -- the stop row: one all-null child per parent (see the header)
    select
        join_parent_key,
        join_parent_view,
        null as wtpart_usage_key,
        null as parent_wtpart_master_key,
        null as parent_part_number,
        null as component_quantity,
        null as spare_part_indicator,
        null as lowest_replaceable_unit,
        null as reference_designator,
        null as component_wtpart_master_key,
        null as part_number,
        null as part_name,
        null as view
    from parents
),

exploded as (
    select
        level_0.component_wtpart_master_key as top_level_wtpart_master_key,
        level_0.part_number as top_level_part_number,
        level_0.part_name || ' ' || level_0.part_number as top_level_parent,
        level_0.view as top_level_view,
        case
            {%- for level in range(max_depth, 0, -1) %}
                when level_{{ level }}.part_number is not null then {{ level }}
            {%- endfor %}
            else 0
        end as level,
        {%- for column in part_columns %}
            case
                {%- for level in range(max_depth, 0, -1) %}
                    when level_{{ level }}.part_number is not null then level_{{ level }}.{{ column }}
                {%- endfor %}
                else level_0.{{ column }}
            end as node_{{ column }},
        {%- endfor %}
        {%- for column in usage_columns %}
            case
                {%- for level in range(max_depth, 0, -1) %}
                    when level_{{ level }}.part_number is not null then level_{{ level }}.{{ column }}
                {%- endfor %}
            end as {{ column }},
        {%- endfor %}
        -- quantity per ONE top-level part: the product of the quantities along the
        -- path, where a level without one (or below the node) counts as 1. Multiplied
        -- as double: the exact product of 21 decimal(13, 3) factors needs scale 63,
        -- more than any DECIMAL type holds, so a decimal product only works where the
        -- engine silently cuts the scale.
        cast(
            round(
                {%- for level in range(1, max_depth + 1) %}
                    {% if not loop.first %}* {% endif %}coalesce(
                        cast(level_{{ level }}.component_quantity as double), 1
                    )
                {%- endfor %},
                3
            ) as decimal(38, 3)
        ) as computed_component_quantity,
        -- part numbers from the top-level part down to the node
        level_0.part_number
        {%- for level in range(1, max_depth + 1) %}
            || coalesce(' -> ' || level_{{ level }}.part_number, '')
        {%- endfor %} as full_parent_hierarchy,
        -- the same path with each usage link's key: the sort order, and what keeps
        -- two uses of one part under one parent apart
        level_0.part_number
        {%- for level in range(1, max_depth + 1) %}
            || coalesce(
                ' -> ' || level_{{ level }}.part_number
                || ' #' || coalesce(cast(level_{{ level }}.wtpart_usage_key as varchar), ''),
                ''
            )
        {%- endfor %} as hierarchy_sort_path,
        -- the node at max_depth still has children, so its subtree was cut off
        overflow.join_parent_key is not null as is_depth_truncated
    from top_level_parts as level_0
    {% for level in range(1, max_depth + 1) -%}
        left join parent_child as level_{{ level }}
            on
                level_{{ level - 1 }}.component_wtpart_master_key = level_{{ level }}.join_parent_key
                and level_{{ level - 1 }}.view = level_{{ level }}.join_parent_view
    {% endfor -%}
    left join parents as overflow
        on
            level_{{ max_depth }}.component_wtpart_master_key = overflow.join_parent_key
            and level_{{ max_depth }}.view = overflow.join_parent_view
),

final as (
    select
        top_level_part_number as part_number,
        top_level_parent,
        top_level_view,
        spare_part_indicator,
        lowest_replaceable_unit,
        parent_part_number,
        parent_wtpart_master_key,
        wtpart_usage_key,
        node_view as view,
        node_part_number as component_number,
        repeat(' |  ', level) || node_part_name as structure_name,
        cast(component_quantity as decimal(13, 3)) as component_quantity,
        computed_component_quantity,
        level,
        node_component_wtpart_master_key as component_wtpart_master_key,
        reference_designator,
        full_parent_hierarchy,
        rank() over (
            order by top_level_view, hierarchy_sort_path
        ) as hierarchy_sort_order,
        is_depth_truncated,
        -- one per row: the top-level part and the usage links down to the node
        md5(
            top_level_view || '|' || cast(top_level_wtpart_master_key as varchar)
            || '|' || hierarchy_sort_path
        ) as bom_path_key,
        -- the node's own parent -> child link, in the node's view
        md5(
            coalesce(cast(node_component_wtpart_master_key as varchar), '')
            || '|' || coalesce(cast(parent_wtpart_master_key as varchar), '')
            || '|' || coalesce(node_view, '')
        ) as parent_child_key
    from exploded
)

select * from final
