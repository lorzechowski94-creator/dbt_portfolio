-- One-time manual bootstrap for Snowflake <-> GitLab OIDC (Workload Identity
-- Federation) auth used by the `prod` dbt target (see ci/profiles.yml).
--
-- Run this ONCE per Snowflake account, as ACCOUNTADMIN, in Snowsight (or
-- SnowSQL). Not executed by CI/CD — this creates the identity CI authenticates
-- as, so it can't bootstrap itself.
--
-- The SQL is identical across all accounts (dev, r1-prod, r2-prod, r3-prod)
-- because SUBJECT is tied to the GitLab project path, which is the same
-- regardless of which Snowflake account the pipeline connects to — the same
-- pattern an infrastructure-as-code service user follows, where one bootstrap
-- is repeated per account.
--
-- The script is idempotent, so re-running the whole thing in an account that
-- was bootstrapped by an older version is the way to pick up new grants.

USE ROLE ACCOUNTADMIN;

-- Sanity-check these names exist in this account before granting against them.
SHOW WAREHOUSES LIKE 'WH_ANALYTICS_REPORTING_XS';
SHOW DATABASES LIKE 'ANALYTICS%';

CREATE USER IF NOT EXISTS SVC_DBT_CI
  TYPE = SERVICE;

ALTER USER SVC_DBT_CI SET WORKLOAD_IDENTITY = (
  TYPE    = OIDC
  ISSUER  = 'https://gitlab.com'
  SUBJECT = 'project_path:your-group/care-analytics-dbt'
);

CREATE ROLE IF NOT EXISTS DBT_TRANSFORMER;
GRANT ROLE DBT_TRANSFORMER TO USER SVC_DBT_CI;
ALTER USER SVC_DBT_CI SET DEFAULT_ROLE = DBT_TRANSFORMER;

GRANT USAGE ON WAREHOUSE WH_ANALYTICS_REPORTING_XS TO ROLE DBT_TRANSFORMER;

GRANT USAGE ON DATABASE ANALYTICS_RAW TO ROLE DBT_TRANSFORMER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE ANALYTICS_RAW TO ROLE DBT_TRANSFORMER;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE ANALYTICS_RAW TO ROLE DBT_TRANSFORMER;
GRANT SELECT ON ALL TABLES IN DATABASE ANALYTICS_RAW TO ROLE DBT_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN DATABASE ANALYTICS_RAW TO ROLE DBT_TRANSFORMER;
GRANT CREATE VIEW, CREATE TABLE ON ALL SCHEMAS IN DATABASE ANALYTICS_RAW TO ROLE DBT_TRANSFORMER;
GRANT CREATE VIEW, CREATE TABLE ON FUTURE SCHEMAS IN DATABASE ANALYTICS_RAW TO ROLE DBT_TRANSFORMER;

GRANT USAGE ON DATABASE ANALYTICS_RAW_ACCESS TO ROLE DBT_TRANSFORMER;
GRANT CREATE SCHEMA ON DATABASE ANALYTICS_RAW_ACCESS TO ROLE DBT_TRANSFORMER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE ANALYTICS_RAW_ACCESS TO ROLE DBT_TRANSFORMER;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE ANALYTICS_RAW_ACCESS TO ROLE DBT_TRANSFORMER;
GRANT SELECT ON ALL TABLES IN DATABASE ANALYTICS_RAW_ACCESS TO ROLE DBT_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN DATABASE ANALYTICS_RAW_ACCESS TO ROLE DBT_TRANSFORMER;
GRANT CREATE VIEW, CREATE TABLE ON ALL SCHEMAS IN DATABASE ANALYTICS_RAW_ACCESS TO ROLE DBT_TRANSFORMER;
GRANT CREATE VIEW, CREATE TABLE ON FUTURE SCHEMAS IN DATABASE ANALYTICS_RAW_ACCESS TO ROLE DBT_TRANSFORMER;

GRANT USAGE ON DATABASE ANALYTICS_STAGING TO ROLE DBT_TRANSFORMER;
GRANT CREATE SCHEMA ON DATABASE ANALYTICS_STAGING TO ROLE DBT_TRANSFORMER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE ANALYTICS_STAGING TO ROLE DBT_TRANSFORMER;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE ANALYTICS_STAGING TO ROLE DBT_TRANSFORMER;
GRANT SELECT ON ALL TABLES IN DATABASE ANALYTICS_STAGING TO ROLE DBT_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN DATABASE ANALYTICS_STAGING TO ROLE DBT_TRANSFORMER;
GRANT CREATE VIEW, CREATE TABLE ON ALL SCHEMAS IN DATABASE ANALYTICS_STAGING TO ROLE DBT_TRANSFORMER;
GRANT CREATE VIEW, CREATE TABLE ON FUTURE SCHEMAS IN DATABASE ANALYTICS_STAGING TO ROLE DBT_TRANSFORMER;

GRANT USAGE ON DATABASE ANALYTICS_INTERMEDIATE TO ROLE DBT_TRANSFORMER;
GRANT CREATE SCHEMA ON DATABASE ANALYTICS_INTERMEDIATE TO ROLE DBT_TRANSFORMER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE ANALYTICS_INTERMEDIATE TO ROLE DBT_TRANSFORMER;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE ANALYTICS_INTERMEDIATE TO ROLE DBT_TRANSFORMER;
GRANT SELECT ON ALL TABLES IN DATABASE ANALYTICS_INTERMEDIATE TO ROLE DBT_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN DATABASE ANALYTICS_INTERMEDIATE TO ROLE DBT_TRANSFORMER;
GRANT CREATE VIEW, CREATE TABLE ON ALL SCHEMAS IN DATABASE ANALYTICS_INTERMEDIATE TO ROLE DBT_TRANSFORMER;
GRANT CREATE VIEW, CREATE TABLE ON FUTURE SCHEMAS IN DATABASE ANALYTICS_INTERMEDIATE TO ROLE DBT_TRANSFORMER;

GRANT USAGE ON DATABASE ANALYTICS_MART TO ROLE DBT_TRANSFORMER;
GRANT CREATE SCHEMA ON DATABASE ANALYTICS_MART TO ROLE DBT_TRANSFORMER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE ANALYTICS_MART TO ROLE DBT_TRANSFORMER;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE ANALYTICS_MART TO ROLE DBT_TRANSFORMER;
GRANT SELECT ON ALL TABLES IN DATABASE ANALYTICS_MART TO ROLE DBT_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN DATABASE ANALYTICS_MART TO ROLE DBT_TRANSFORMER;
GRANT CREATE VIEW, CREATE TABLE ON ALL SCHEMAS IN DATABASE ANALYTICS_MART TO ROLE DBT_TRANSFORMER;
GRANT CREATE VIEW, CREATE TABLE ON FUTURE SCHEMAS IN DATABASE ANALYTICS_MART TO ROLE DBT_TRANSFORMER;

-- CREATE SEMANTIC VIEW is a DISTINCT privilege from CREATE VIEW — macros/create_semantic_views.sql
-- needs it on the report schema. Without it the DDL only succeeds where DBT_TRANSFORMER happens to
-- OWN the schema (it holds CREATE SCHEMA above, so it does in accounts where it created it), which
-- is luck rather than a contract: a freshly bootstrapped account would fail.
GRANT CREATE SEMANTIC VIEW ON ALL SCHEMAS IN DATABASE ANALYTICS_MART TO ROLE DBT_TRANSFORMER;
GRANT CREATE SEMANTIC VIEW ON FUTURE SCHEMAS IN DATABASE ANALYTICS_MART TO ROLE DBT_TRANSFORMER;

-- Verify:
DESC USER SVC_DBT_CI; -- HAS_WORKLOAD_IDENTITY should be true, DEFAULT_ROLE should be DBT_TRANSFORMER
SHOW GRANTS TO ROLE DBT_TRANSFORMER;
